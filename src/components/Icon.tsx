interface IconProps {
  name: string;
  className?: string;
  strokeWidth?: number;
}

export function Icon({ name, className = "h-6 w-6", strokeWidth = 1.6 }: IconProps) {
  const Component = ICONS[name] ?? Info;
  return <Component className={className} strokeWidth={strokeWidth} aria-hidden="true" />;
}
